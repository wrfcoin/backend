/**
 * Advisory governance relay contract (core4 `advisory_governance`, core4#143 + #146).
 *
 * The browser signs a `SignedAdvisoryAction` itself: with the wallet's 12-word (ed25519) key, or with
 * its passkey (a WebAuthn assertion over `sha3_256(advisory_action_message)`). The node takes it only
 * inside a whole `AdvisoryGovernance` Transaction at POST /governance/advisory/submit, so this module
 * wraps it exactly as the core4 CLI does (`wrfcoin governance advisory`, tools/cli commands/advisory.rs
 * build_transaction): one outpoint per (account, nonce), a zero OP_TRUE output to the account, tx nonce
 * = action nonce, `data` = the signed action's JSON, id = `Transaction::calculate_hash`. The wrapper
 * adds no signature; the one inside `data` is the only authorization, and core4 verifies it.
 *
 * Here: shape, sizes, the text rules, and that the signing key (or passkey credential) derives the
 * account, so a malformed body never costs the node a verification. Every other transaction type is
 * unrepresentable: the body is a signed advisory action, never a transaction.
 *
 * Pinned by contract-fixtures/advisory-governance-relay-vectors.json (generated by core4 itself).
 */
import { createHash } from 'node:crypto';

export const MAX_ADVISORY_BODY_BYTES = 16 * 1024;
/** core4 MAX_ADVISORY_PAYLOAD_BYTES. */
export const MAX_ADVISORY_DATA_BYTES = 8 * 1024;
export const MAX_TITLE_BYTES = 160;
export const MAX_SUMMARY_BYTES = 1024;
/** core4 MAX_WEBAUTHN_FIELD_LEN. */
const MAX_WEBAUTHN_FIELD_BYTES = 4096;

const OUTPOINT_DOMAIN = Buffer.from('wrfcoin.advisory_governance.outpoint.v1');
const TX_HASH_TAG = Buffer.from('wrfcoin_tx_hash_v1');
const PASSKEY_ADDRESS_DOMAIN = Buffer.from('wrfcoin.passkey_address.v1');
const PROPOSAL_ID_RE = /^adv-[0-9a-f]{16}$/;
const TOP_MEMBERS = new Set(['account', 'action', 'nonce', 'public_key', 'signature', 'passkey']);
const PASSKEY_FIXED: Record<string, number> = { public_key_p256: 64, rp_id_hash: 32 };
const PASSKEY_VARIABLE = ['authenticator_data', 'client_data_json', 'signature'];
const PASSKEY_MEMBERS = new Set([...Object.keys(PASSKEY_FIXED), ...PASSKEY_VARIABLE]);

export type AdvisoryActionJson =
  | { propose: { title: string; summary: string } }
  | { vote: { proposal_id: string; approve: boolean } };

export interface PasskeyAuthJson {
  public_key_p256: string;
  rp_id_hash: string;
  authenticator_data: string;
  client_data_json: string;
  signature: string;
}

/** `SignedAdvisoryAction` in serde member order (ed25519 xor passkey). */
export type SignedAdvisoryActionJson =
  | { account: number[]; action: AdvisoryActionJson; nonce: number; public_key: string; signature: string }
  | { account: number[]; action: AdvisoryActionJson; nonce: number; passkey: PasskeyAuthJson };

export type ParsedAdvisory =
  | { ok: true; account: string; kind: 'propose' | 'vote'; signer: 'ed25519' | 'passkey'; value: SignedAdvisoryActionJson }
  | { ok: false; message: string };

const fail = (message: string): ParsedAdvisory => ({ ok: false, message });
const isPlainObject = (v: unknown): v is Record<string, unknown> => !!v && typeof v === 'object' && !Array.isArray(v);
// Lowercase only: core4#146 accepts one encoding per action (no uppercase hex, no empty or null members).
const isHexOf = (v: unknown, bytes: number): v is string =>
  typeof v === 'string' && v.length === bytes * 2 && /^[0-9a-f]*$/.test(v);
const isHexUpTo = (v: unknown, maxBytes: number): v is string =>
  typeof v === 'string' && v.length > 0 && v.length % 2 === 0 && v.length <= maxBytes * 2 && /^[0-9a-f]*$/.test(v);
const sha3 = (buf: Buffer): Buffer => createHash('sha3-256').update(buf).digest();

/** core4 Address::from_public_key (ed25519): 0x + hex(SHA3-256(pubkey)[..20]). */
export function ed25519Address(publicKeyHex: string): string {
  return `0x${sha3(Buffer.from(publicKeyHex, 'hex')).subarray(0, 20).toString('hex')}`;
}

/** core4 passkey_address_from_parts: 0x + hex(SHA3-256(domain ‖ rp_id_hash ‖ 0x04 ‖ X ‖ Y)[..20]). */
export function passkeyAddress(rpIdHashHex: string, publicKeyXyHex: string): string {
  const digest = sha3(Buffer.concat([PASSKEY_ADDRESS_DOMAIN, Buffer.from(rpIdHashHex, 'hex'), Buffer.from([0x04]), Buffer.from(publicKeyXyHex, 'hex')]));
  return `0x${digest.subarray(0, 20).toString('hex')}`;
}

/** core4 serde Address (JSON array of 20 bytes) → lowercase 0x address, or null. */
function byteArrayToAddress(value: unknown): string | null {
  if (!Array.isArray(value) || value.length !== 20 || !value.every((b) => Number.isInteger(b) && b >= 0 && b <= 255)) return null;
  return `0x${Buffer.from(value as number[]).toString('hex')}`;
}

/**
 * core4 `forbidden_char`: C0 controls (`\n` allowed in a summary), DEL and C1, and the bidi
 * embedding/override/isolate characters. Byte rule only, no normalization.
 */
function forbiddenChar(text: string, allowNewline: boolean): number | null {
  for (const ch of text) {
    const cp = ch.codePointAt(0)!;
    if (ch === '\n') { if (!allowNewline) return cp; continue; }
    if (cp <= 0x1f || (cp >= 0x7f && cp <= 0x9f) || (cp >= 0x202a && cp <= 0x202e) || (cp >= 0x2066 && cp <= 0x2069)) return cp;
  }
  return null;
}

/** Title/summary rules, as core4 `validate_text`. Returns a refusal or null. */
export function textProblem(field: 'title' | 'summary', text: unknown): string | null {
  if (typeof text !== 'string') return `${field} must be a string`;
  if (text.trim() === '') return `${field} is empty`;
  const max = field === 'title' ? MAX_TITLE_BYTES : MAX_SUMMARY_BYTES;
  const bytes = Buffer.byteLength(text, 'utf8');
  if (bytes > max) return `${field} is ${bytes} bytes, over the ${max}-byte limit`;
  // A lone surrogate cannot be UTF-8 encoded faithfully; refuse it rather than let it turn into U+FFFD.
  if (/[\uD800-\uDFFF]/u.test(text.replace(/[\uD800-\uDBFF][\uDC00-\uDFFF]/g, ''))) return `${field} is not valid Unicode`;
  const cp = forbiddenChar(text, field === 'summary');
  if (cp !== null) return `${field}: character U+${cp.toString(16).toUpperCase().padStart(4, '0')} is not allowed`;
  return null;
}

function parseAction(raw: unknown): { ok: true; kind: 'propose' | 'vote'; value: AdvisoryActionJson } | { ok: false; message: string } {
  if (!isPlainObject(raw)) return { ok: false, message: 'action must be an object' };
  const keys = Object.keys(raw);
  if (keys.length !== 1) return { ok: false, message: 'action must be exactly one of propose or vote' };
  if (keys[0] === 'propose') {
    const p = raw.propose;
    if (!isPlainObject(p) || Object.keys(p).some((k) => k !== 'title' && k !== 'summary')) {
      return { ok: false, message: 'propose takes title and summary only' };
    }
    const problem = textProblem('title', p.title) ?? textProblem('summary', p.summary);
    if (problem) return { ok: false, message: problem };
    return { ok: true, kind: 'propose', value: { propose: { title: p.title as string, summary: p.summary as string } } };
  }
  if (keys[0] === 'vote') {
    const v = raw.vote;
    if (!isPlainObject(v) || Object.keys(v).some((k) => k !== 'proposal_id' && k !== 'approve')) {
      return { ok: false, message: 'vote takes proposal_id and approve only' };
    }
    if (typeof v.proposal_id !== 'string' || !PROPOSAL_ID_RE.test(v.proposal_id)) {
      return { ok: false, message: 'proposal_id must be an advisory id (adv- and 16 hex digits)' };
    }
    if (typeof v.approve !== 'boolean') return { ok: false, message: 'approve must be true or false' };
    return { ok: true, kind: 'vote', value: { vote: { proposal_id: v.proposal_id, approve: v.approve } } };
  }
  return { ok: false, message: 'action must be propose or vote' };
}

function passkeyProblem(value: unknown): string | null {
  if (!isPlainObject(value)) return 'passkey must be an object';
  for (const key of Object.keys(value)) if (!PASSKEY_MEMBERS.has(key)) return `passkey has an unknown member: ${key.slice(0, 32)}`;
  for (const [key, bytes] of Object.entries(PASSKEY_FIXED)) {
    if (!isHexOf(value[key], bytes)) return `passkey.${key} must be ${bytes} bytes of hex`;
  }
  for (const key of PASSKEY_VARIABLE) {
    if (!isHexUpTo(value[key], MAX_WEBAUTHN_FIELD_BYTES)) return `passkey.${key} must be non-empty even-length hex of at most ${MAX_WEBAUTHN_FIELD_BYTES} bytes`;
  }
  return null;
}

/** Parse the browser's signed advisory action. The returned `value` is rebuilt member by member. */
export function parseSignedAdvisoryAction(body: unknown): ParsedAdvisory {
  if (!isPlainObject(body)) return fail('JSON body required');
  for (const key of Object.keys(body)) if (!TOP_MEMBERS.has(key)) return fail(`unknown member: ${key.slice(0, 32)}`);
  const account = byteArrayToAddress(body.account);
  if (!account) return fail('account must be a 20-byte array');
  if (!Number.isSafeInteger(body.nonce) || (body.nonce as number) < 0) return fail('nonce must be a non-negative integer');
  const nonce = body.nonce as number;
  const action = parseAction(body.action);
  if (action.ok === false) return fail(action.message);
  const accountBytes = [...Buffer.from(account.slice(2), 'hex')];
  // Absent is the only "not this form": explicit null or "" members are refused (core4 one-encoding rule).
  if (body.passkey === null) return fail('passkey must be absent or an object, not null');
  if (body.public_key === '' || body.signature === '') return fail('public_key and signature must be absent or non-empty');
  const hasEd = body.public_key !== undefined || body.signature !== undefined;
  const hasPasskey = body.passkey !== undefined;
  if (hasEd === hasPasskey) return fail('exactly one of public_key + signature or passkey is required');
  if (hasPasskey) {
    const problem = passkeyProblem(body.passkey);
    if (problem) return fail(problem);
    const p = body.passkey as Record<string, string>;
    if (passkeyAddress(p.rp_id_hash, p.public_key_p256) !== account) return fail('passkey credential does not derive to account');
    return {
      ok: true, account, kind: action.kind, signer: 'passkey',
      value: {
        account: accountBytes, action: action.value, nonce,
        passkey: {
          public_key_p256: p.public_key_p256, rp_id_hash: p.rp_id_hash, authenticator_data: p.authenticator_data,
          client_data_json: p.client_data_json, signature: p.signature,
        },
      },
    };
  }
  if (!isHexOf(body.public_key, 32)) return fail('public_key must be a 32-byte ed25519 public key in lowercase hex');
  if (!isHexOf(body.signature, 64)) return fail('signature must be a 64-byte ed25519 signature in lowercase hex');
  if (ed25519Address(body.public_key) !== account) return fail('public_key does not derive to account');
  return {
    ok: true, account, kind: action.kind, signer: 'ed25519',
    value: { account: accountBytes, action: action.value, nonce, public_key: body.public_key, signature: body.signature },
  };
}

function u32le(n: number): Buffer { const b = Buffer.alloc(4); b.writeUInt32LE(n); return b; }
function u64le(n: number | bigint): Buffer { const b = Buffer.alloc(8); b.writeBigUInt64LE(BigInt(n)); return b; }
function i64le(n: number | bigint): Buffer { const b = Buffer.alloc(8); b.writeBigInt64LE(BigInt(n)); return b; }
const hashJson = (bytes: Buffer) => ({ hash_type: 'Sha3', bytes: [...bytes] });
function lenStr(value: string): Buffer { const bytes = Buffer.from(value, 'utf8'); return Buffer.concat([u32le(bytes.length), bytes]); }
function optionalStr(value: string | null): Buffer {
  return value === null ? Buffer.from([0]) : Buffer.concat([Buffer.from([1]), lenStr(value)]);
}

/** chrono's serde form of a whole-second DateTime<Utc>. */
function rfc3339Seconds(unixSeconds: number): string {
  return new Date(unixSeconds * 1000).toISOString().replace('.000Z', 'Z');
}

export interface BuiltAdvisoryTransaction {
  body: Record<string, unknown>;
  txId: string;
}

/** The `Transaction` JSON core4's POST /governance/advisory/submit takes (CLI build_transaction). */
export function buildAdvisoryTransaction(signed: SignedAdvisoryActionJson, submittedAtSeconds: number): BuiltAdvisoryTransaction {
  if (!Number.isSafeInteger(submittedAtSeconds) || submittedAtSeconds < 0) throw new Error('submittedAtSeconds must be unix seconds');
  const accountBytes = Buffer.from(signed.account);
  const account = `0x${accountBytes.toString('hex')}`;
  const data = JSON.stringify(signed);
  if (Buffer.byteLength(data) > MAX_ADVISORY_DATA_BYTES) throw new Error('signed action is too large');
  const outpoint = sha3(Buffer.concat([OUTPOINT_DOMAIN, accountBytes, u64le(signed.nonce)]));
  const inputPublicKey = 'public_key' in signed ? signed.public_key : null;
  const parts = [
    TX_HASH_TAG, lenStr('AdvisoryGovernance'), u32le(1), i64le(submittedAtSeconds * 1000), u64le(1),
    outpoint, u32le(0), optionalStr(null), optionalStr(inputPublicKey), optionalStr(null),
    u64le(1), u64le(0), lenStr(account), lenStr('OP_TRUE'), Buffer.from([0]),
    optionalStr(data), Buffer.from([0]), u64le(0), u64le(signed.nonce),
  ];
  const id = sha3(Buffer.concat(parts));
  return {
    txId: id.toString('hex'),
    body: {
      id: hashJson(id),
      tx_type: 'AdvisoryGovernance',
      version: 1,
      timestamp: rfc3339Seconds(submittedAtSeconds),
      inputs: [{ txid: hashJson(outpoint), vout: 0, signature: null, public_key: inputPublicKey, coinbase_data: null }],
      outputs: [{ amount: 0, address: account, script: 'OP_TRUE', nft_data: null }],
      data,
      lock_time: null,
      fee: 0,
      sender_address: [...accountBytes],
      recipient_address: null,
      amount: 0,
      operation: { Transfer: { amount: 0 } },
      nonce: signed.nonce,
    },
  };
}
